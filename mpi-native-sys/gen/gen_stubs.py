#!/usr/bin/env python3
"""Generate src/stubs.rs: a panic stub for every name in mpi-rt-sys's `ffi` surface that
the hand-written carried set (src/functions.rs, src/constants.rs) does not define.

Usage: python3 gen/gen_stubs.py <path-to-mpi-rt-sys/src> > src/stubs.rs

The signature list comes from the retired `mpi-rt-sys` crate, which carried rsmpi-rt's
complete `ffi` surface. Fetch it with `cargo download mpi-rt-sys@0.1.0` (or read
`~/.cargo/registry/src/*/mpi-rt-sys-0.1.0/src` after any build that used it) and pass its
`src` directory. Run once when that surface changes; the output is checked in.
"""
import io, re, subprocess, sys, pathlib

old = pathlib.Path(sys.argv[1])
here = pathlib.Path(__file__).resolve().parent.parent / "src"

def items(text):
    out = {}
    for m in re.finditer(r'^pub (unsafe fn|fn) (\w+)\((.*?)\)(\s*->\s*[^{]+?)?\s*\{', text, re.S | re.M):
        kind, name, args, ret = m.groups()
        out[name] = (kind, re.sub(r'\s+', ' ', args).strip(), (ret or '').strip())
    return out

old_items = {}
for f in ("functions.rs", "constants.rs"):
    old_items.update(items((old / f).read_text()))

carried = set()
fn_src = (here / "functions.rs").read_text()
carried |= set(re.findall(r'thunk!\((\w+)', fn_src))
carried |= set(re.findall(r'pub unsafe fn (\w+)', fn_src))
c_src = (here / "constants.rs").read_text()
for a, b in re.findall(r'constant!\(\s*(\w+),\s*(\w+),', c_src):
    carried |= {a, b}
carried |= set(re.findall(r'pub (?:unsafe )?fn (\w+)', c_src))

out = io.StringIO()
_print = print


def print(*args, file=None, **kw):  # noqa: A001 - route stdout into the buffer
    _print(*args, file=file if file is not None else out, **kw)


print("//! Panic stubs for every `ffi` name outside the carried set.")
print("//!")
print("//! Generated by `gen/gen_stubs.py` from the `mpi-rt-sys` signature list; do not edit.")
print("//! A stub panics with [`crate::UnsupportedMpiCall`], which the tenferro C boundary")
print("//! catches (D10). Reaching one is counted by [`crate::stub_hits`].")
print()
print("#![allow(unused_variables, clippy::too_many_arguments)]")
print("use std::os::raw::*;")
print()
print("use crate::callback_types::*;")
print("use crate::types::*;")
print()
count = 0
for name in sorted(old_items):
    if name in carried:
        continue
    kind, args, ret = old_items[name]
    arglist = args.rstrip(',')
    print(f"pub {kind} {name}({arglist}) {ret} {{".replace(")  {", ") {"))
    print(f"    crate::stub(\"{name}\")")
    print("}")
    print()
    count += 1
_print(f"// {count} stubs", file=sys.stderr)

# A generated file that `cargo fmt --check` disagrees with fails CI on the next regeneration,
# so the generator emits exactly what rustfmt would produce: nightly rustfmt, the workspace
# config and the doc-comment flag that .github/workflows/lint.yaml passes.
root = here.parent.parent
formatted = subprocess.run(
    ["rustup", "run", "nightly", "rustfmt", "--edition", "2021", "--config-path", str(root),
     "--config", "format_code_in_doc_comments=true", "--emit", "stdout"],
    input=out.getvalue(), capture_output=True, text=True, check=True,
).stdout
sys.stdout.write(formatted)
